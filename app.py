from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
from sklearn.metrics import accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix, classification_report

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT 
FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "knearest_neighbors.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}
st.set_page_config(page_title="ML Model Evaluation", page_icon="📊", layout="wide")
st.title("Machine Learning Classification Model Evaluation")
st.write("Upload a labelled test CSV. Saved models are loaded without retraining.")
if any(not (MODEL_DIR / f).exists() for f in FILES.values()):
    st.error("Model files missing. Run the training script first.")
    st.stop()
uploaded = st.file_uploader("Upload test CSV", type=["csv"])
choice = st.selectbox("Select classifier", list(FILES))
if uploaded is None:
    st.info("Upload test_data.csv generated by the training script.")
    st.stop()
try:
    data = pd.read_csv(uploaded)
    bundle = joblib.load(MODEL_DIR / FILES[choice])
    model, features, target = bundle["model"], bundle["feature_columns"], bundle["target_col"]
    missing = [c for c in features + [target] if c not in data.columns]
    if missing:
        st.error("Missing columns: " + ", ".join(missing))
        st.stop()
    X, y = data[features], data[target]
    pred = model.predict(X)
    idx = list(model.classes_).index(1)
    score = model.predict_proba(X)[:, idx] if hasattr(model, "predict_proba") else model.decision_function(X)
    if not hasattr(model, "predict_proba") and idx != 1:
        score = -score
    metrics = {
        "Accuracy": accuracy_score(y, pred), "AUC": roc_auc_score(y, score),
        "Precision": precision_score(y, pred, zero_division=0),
        "Recall": recall_score(y, pred, zero_division=0),
        "F1 Score": f1_score(y, pred, zero_division=0),
        "MCC": matthews_corrcoef(y, pred)
    }
    st.subheader(choice + " – Metrics")
    cols = st.columns(3)
    for i, (label, value) in enumerate(metrics.items()):
        cols[i % 3].metric(label, f"{value:.4f}")
    st.subheader("Confusion Matrix")
    labels = sorted(pd.unique(pd.concat([y, pd.Series(pred)])))
    st.dataframe(pd.DataFrame(confusion_matrix(y, pred, labels=labels),
        index=[f"Actual {v}" for v in labels], columns=[f"Predicted {v}" for v in labels]), use_container_width=True)
    st.subheader("Classification Report")
    st.dataframe(pd.DataFrame(classification_report(y, pred, output_dict=True, zero_division=0)).transpose().round(4), use_container_width=True)
except Exception as error:
    st.error(f"Evaluation failed: {error}")
